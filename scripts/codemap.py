#!/usr/bin/env python3
"""
Codebase map generator for agents.

Builds the generated files in docs/codemap/ from what the code already says:
- the first line of each file's leading /** */ docblock (its purpose),
- every "NN-name.md" spec reference in the file (optionally followed by " - Section"),
- the exported HTTP handlers of each Next.js API route.

Usage:
  python3 scripts/codemap.py          # regenerate docs/codemap/*.md
  python3 scripts/codemap.py --check  # exit 1 if the committed map is stale

Standard library only. Output is deterministic (sorted, no timestamps).
"""

import re
import subprocess
import sys
from collections import defaultdict
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
OUT_DIR = REPO_ROOT / "docs" / "codemap"
SPECS_DIR = REPO_ROOT / "nextjs" / "specs"
SRC_PREFIX = "nextjs/src/"
API_PREFIX = "nextjs/src/app/api/"
UI_PREFIX = "nextjs/src/components/ui/"
GENERATED_NOTE = "<!-- Generated by scripts/codemap.py. Do not edit by hand. -->\n"

SPEC_REF_RE = re.compile(r"\b(\d{2}-[a-z0-9-]+)\.md(?:\s+-\s+([^\n*]+))?")
HTTP_METHOD_RE = re.compile(
    r"export\s+(?:async\s+function\s+|function\s+|const\s+)(GET|POST|PUT|PATCH|DELETE)\b"
)


def list_tracked_files() -> list[str]:
    """
    Lists the source files the map covers.

    Returns:
        Repo-relative paths of tracked TS/TSX files in nextjs/src and ws-server,
        excluding translation messages.
    """
    output = subprocess.run(
        ["git", "ls-files", "nextjs/src", "ws-server"],
        cwd=REPO_ROOT, capture_output=True, text=True, check=True,
    ).stdout
    return sorted(
        path for path in output.splitlines()
        if path.endswith((".ts", ".tsx")) and "/i18n/messages/" not in path
    )


def read_purpose(text: str) -> str:
    """
    Extracts a file's purpose from its leading docblock.

    Args:
        text: Full file contents.

    Returns:
        The first non-empty line of the leading /** */ comment, or "" if none.
    """
    stripped = re.sub(r'^\s*["\']use (client|server)["\'];?\s*', "", text)
    match = re.match(r"\s*/\*\*(.*?)\*/", stripped, re.DOTALL)
    if not match:
        return ""
    for line in match.group(1).splitlines():
        cleaned = line.strip().lstrip("*").strip()
        if cleaned and not cleaned.lower().startswith("spec"):
            return cleaned
    return ""


def read_spec_refs(text: str) -> dict[str, set[str]]:
    """
    Collects every spec reference in a file.

    Args:
        text: Full file contents.

    Returns:
        Map of spec name (e.g. "16-games") to the set of section names cited with it.
    """
    refs: dict[str, set[str]] = defaultdict(set)
    for spec, section in SPEC_REF_RE.findall(text):
        refs[spec]
        if section:
            refs[spec].add(section.strip().rstrip("."))
    return refs


def route_path(file_path: str) -> str:
    """
    Converts an API route file path to its URL path.

    Args:
        file_path: Repo-relative path ending in /route.ts.

    Returns:
        The URL, e.g. "/api/games/:gameId/start".
    """
    folder = file_path[len("nextjs/src/app"):-len("/route.ts")]
    return re.sub(r"\[([^\]]+)\]", r":\1", folder)


def short(file_path: str) -> str:
    """Strips the nextjs/src/ prefix to keep tables narrow."""
    return file_path[len(SRC_PREFIX):] if file_path.startswith(SRC_PREFIX) else file_path


def read_specs() -> tuple[dict[str, str], dict[str, set[str]]]:
    """
    Reads the title and section headings of every spec file.

    Returns:
        A pair: map of spec name to its title (without the "NN — " prefix),
        and map of spec name to its lower-cased section headings.
    """
    titles: dict[str, str] = {}
    headings: dict[str, set[str]] = {}
    for spec_file in sorted(SPECS_DIR.glob("*.md")):
        spec_headings = [
            line.lstrip("#").strip()
            for line in spec_file.read_text(encoding="utf-8").splitlines()
            if line.startswith("#")
        ]
        title = spec_headings[0] if spec_headings else ""
        titles[spec_file.stem] = re.sub(r"^\d{2}\s*[—-]\s*", "", title)
        headings[spec_file.stem] = {h.lower() for h in spec_headings[1:]}
    return titles, headings


def known_sections(cited: set[str], spec_headings: set[str]) -> list[str]:
    """
    Keeps only the cited sections that name a real heading of the spec.

    Inline comments often follow the spec name with prose, so a citation counts
    only if, cut at the first comma or semicolon, it matches a heading.

    Args:
        cited: Section texts found after the spec name in a file.
        spec_headings: Lower-cased headings of that spec.

    Returns:
        Sorted, de-duplicated heading names.
    """
    sections = set()
    for text in cited:
        candidate = re.split(r"[,;(]", text)[0].strip().rstrip(".:")
        if candidate.lower() in spec_headings:
            sections.add(candidate)
    return sorted(sections)


def build_specs_md(files: list[str], purposes: dict[str, str],
                   refs: dict[str, dict[str, set[str]]]) -> str:
    """Builds specs.md: spec -> files that reference it, plus unmapped files."""
    titles, headings = read_specs()
    by_spec: dict[str, list[str]] = defaultdict(list)
    for path in files:
        for spec in refs[path]:
            by_spec[spec].append(path)

    lines = [GENERATED_NOTE, "# Spec → code\n\n",
             "Files that cite each spec (header or inline `Spec:` comments). "
             "Spec sections they cite are in brackets. Specs live in `nextjs/specs/`.\n"]
    for spec in sorted(set(titles) | set(by_spec)):
        title = titles.get(spec, "(spec file not found)")
        lines.append(f"\n## {spec}.md — {title}\n\n")
        if not by_spec[spec]:
            lines.append("_No file references this spec._\n")
            continue
        for path in sorted(by_spec[spec]):
            sections = known_sections(refs[path][spec], headings.get(spec, set()))
            suffix = f" [{'; '.join(sections)}]" if sections else ""
            purpose = f" — {purposes[path]}" if purposes[path] else ""
            lines.append(f"- `{short(path)}`{purpose}{suffix}\n")

    unmapped = [p for p in files if not refs[p] and not p.startswith(UI_PREFIX)]
    lines.append(f"\n## Unmapped files ({len(unmapped)})\n\n"
                 "No spec reference in the file. See `files.md` for their purpose.\n\n")
    lines.extend(f"- `{short(p)}`\n" for p in unmapped)
    return "".join(lines)


def build_api_md(files: list[str], purposes: dict[str, str], texts: dict[str, str]) -> str:
    """Builds api.md: one row per API route with methods, file and purpose."""
    lines = [GENERATED_NOTE, "# API routes\n\n",
             "Paths are under `nextjs/src/app`. Helpers shared by routes live next to them "
             "(see `files.md`, section `app/api`).\n\n",
             "| Methods | Path | Purpose |\n|---|---|---|\n"]
    for path in files:
        if path.startswith(API_PREFIX) and path.endswith("/route.ts"):
            methods = sorted(set(HTTP_METHOD_RE.findall(texts[path])),
                             key=["GET", "POST", "PUT", "PATCH", "DELETE"].index)
            lines.append(f"| {' '.join(methods)} | `{route_path(path)}` | "
                         f"{purposes[path] or '—'} |\n")
    return "".join(lines)


def build_files_md(files: list[str], purposes: dict[str, str]) -> str:
    """Builds files.md: files grouped by directory with their purpose."""
    by_dir: dict[str, list[str]] = defaultdict(list)
    for path in files:
        by_dir[str(Path(short(path)).parent)].append(path)

    lines = [GENERATED_NOTE, "# Files by directory\n\n",
             "Paths are relative to `nextjs/src/` unless they start with `ws-server/`. "
             "Files without a purpose have no header docblock.\n"]
    for directory in sorted(by_dir):
        paths = by_dir[directory]
        lines.append(f"\n## {directory}\n\n")
        if directory == "components/ui":
            names = ", ".join(Path(p).stem for p in paths)
            lines.append(f"shadcn/ui primitives (reuse these): {names}\n")
            continue
        for path in paths:
            purpose = f" — {purposes[path]}" if purposes[path] else ""
            lines.append(f"- `{Path(path).name}`{purpose}\n")
    return "".join(lines)


def build_migrations_md() -> str:
    """Builds migrations.md: Flyway version -> file name."""
    output = subprocess.run(
        ["git", "ls-files", "database-migrations"],
        cwd=REPO_ROOT, capture_output=True, text=True, check=True,
    ).stdout
    sql_files = [p for p in output.splitlines() if p.endswith(".sql")]

    def version_key(path: str) -> tuple[int, ...]:
        match = re.match(r"V([\d_]+)__", Path(path).name)
        return tuple(int(n) for n in match.group(1).split("_")) if match else (0,)

    lines = [GENERATED_NOTE, "# Database migrations\n\n",
             "Base schema: `database/`. What each migration does: "
             "`docs/database/migrations.md`.\n\n",
             "| Version | File |\n|---|---|\n"]
    for path in sorted(sql_files, key=version_key):
        name = Path(path).name
        version = name.split("__")[0]
        lines.append(f"| {version} | `{name}` |\n")
    return "".join(lines)


def generate() -> dict[str, str]:
    """
    Builds all generated map files.

    Returns:
        Map of output file name to its contents.
    """
    files = list_tracked_files()
    texts = {p: (REPO_ROOT / p).read_text(encoding="utf-8") for p in files}
    purposes = {p: read_purpose(texts[p]) for p in files}
    refs = {p: read_spec_refs(texts[p]) for p in files}
    return {
        "specs.md": build_specs_md(files, purposes, refs),
        "api.md": build_api_md(files, purposes, texts),
        "files.md": build_files_md(files, purposes),
        "migrations.md": build_migrations_md(),
    }


def main() -> int:
    """Writes the map, or with --check reports whether it is stale."""
    outputs = generate()
    if "--check" in sys.argv[1:]:
        stale = [name for name, content in outputs.items()
                 if not (OUT_DIR / name).exists()
                 or (OUT_DIR / name).read_text(encoding="utf-8") != content]
        if stale:
            print(f"Codemap is stale: {', '.join(stale)}. Run: python3 scripts/codemap.py")
            return 1
        print("Codemap is up to date.")
        return 0
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    for name, content in outputs.items():
        (OUT_DIR / name).write_text(content, encoding="utf-8")
    print(f"Wrote {len(outputs)} files to {OUT_DIR.relative_to(REPO_ROOT)}/")
    return 0


if __name__ == "__main__":
    sys.exit(main())
